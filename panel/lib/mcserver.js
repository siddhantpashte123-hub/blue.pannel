'use strict';

const fs = require('fs');
const path = require('path');
const { spawn, spawnSync } = require('child_process');
const { EventEmitter } = require('events');
const { ensureDir, readJson, writeJson, isPortFree, stamp, formatBytes } = require('./util');
const system = require('./system');

const LOG_LIMIT = 500;
const JAVA_FLAGS = [
  '-XX:+UseG1GC',
  '-XX:+ParallelRefProcEnabled',
  '-XX:MaxGCPauseMillis=150',
  '-XX:+UnlockExperimentalVMOptions',
  '-XX:+DisableExplicitGC',
  '-XX:G1HeapRegionSize=8M',
  '-XX:G1NewSizePercent=30',
  '-XX:G1MaxNewSizePercent=40',
  '-XX:G1ReservePercent=20',
  '-Dfile.encoding=UTF-8'
];

const PLAYER_JOIN = /(?:^|\]:?\s*)([A-Za-z0-9_]{1,16}) joined the game/;
const PLAYER_LEAVE = /(?:^|\]:?\s*)([A-Za-z0-9_]{1,16}) (left the game|lost connection)/;

class MinecraftServer extends EventEmitter {
  constructor(meta) {
    super();
    this.id = meta.id;
    this.name = meta.name;
    this.dir = meta.dir;
    this.port = Number(meta.port);
    this.version = meta.version;
    this.type = meta.type || 'vanilla';
    this.memory = Number(meta.memory) || 1024;
    this.jar = meta.jar || 'server.jar';
    this.createdAt = meta.createdAt || Date.now();
    this.autoRestart = !!meta.autoRestart;
    this.eula = meta.eula !== false;

    this.proc = null;
    this.status = 'stopped';
    this.startedAt = null;
    this.exitedAt = null;
    this.exitCode = null;
    this.players = new Set();
    this.logs = [];
    this.lastError = null;
    this.adopted = false;
    this.adoptedPid = null;
    this.stopping = false;
    this._prevStats = null;
    this.stats = { cpu: 0, memory: 0 };
    this._restarts = [];
    this.hydrateLogs();
  }

  hydrateLogs() {
    try {
      const file = path.join(this.dir, 'console.log');
      if (!fs.existsSync(file)) return;
      const stat = fs.statSync(file);
      const start = Math.max(0, stat.size - 48 * 1024);
      const fd = fs.openSync(file, 'r');
      const buf = Buffer.alloc(stat.size - start);
      fs.readSync(fd, buf, 0, buf.length, start);
      fs.closeSync(fd);
      const lines = buf.toString('utf8').split(/\r?\n/).filter((l) => l.trim()).slice(-120);
      for (const line of lines) {
        this.logs.push({ t: stat.mtimeMs, line: line });
      }
    } catch (err) { /* ignore */ }
  }

  meta() {
    return {
      id: this.id,
      name: this.name,
      dir: this.dir,
      port: this.port,
      version: this.version,
      type: this.type,
      memory: this.memory,
      jar: this.jar,
      createdAt: this.createdAt,
      autoRestart: this.autoRestart,
      eula: this.eula
    };
  }

  jarPath() {
    const candidate = path.join(this.dir, this.jar);
    if (fs.existsSync(candidate)) return candidate;
    const jars = fs.readdirSync(this.dir).filter((f) => f.endsWith('.jar'));
    return jars.length ? path.join(this.dir, jars[0]) : candidate;
  }

  pushLine(line, silent) {
    const entry = { t: Date.now(), line: String(line).replace(/\r$/, '') };
    this.logs.push(entry);
    if (this.logs.length > LOG_LIMIT) this.logs.shift();
    if (/ERROR|Exception|Caused by|FAILED TO|Error:/.test(entry.line) && !/^\s+at\s/.test(entry.line)) {
      this.lastError = { t: entry.t, line: entry.line };
    }
    try {
      fs.appendFileSync(path.join(this.dir, 'console.log'), entry.line + '\n');
    } catch (err) { /* ignore */ }
    if (!silent) this.emit('log', entry);
    return entry;
  }

  clearError() {
    this.lastError = null;
  }

  setStatus(status) {
    if (this.status === status) return;
    this.status = status;
    this.emit('state', this.snapshot());
  }

  async waitForPortFree(timeoutMs) {
    const deadline = Date.now() + (timeoutMs || 15000);
    while (Date.now() < deadline) {
      if (await isPortFree(this.port)) return true;
      await new Promise((r) => setTimeout(r, 400));
    }
    return false;
  }

  writeEula() {
    try {
      fs.writeFileSync(path.join(this.dir, 'eula.txt'),
        '# Generated by BLUENODES\neula=' + (this.eula ? 'true' : 'false') + '\n');
    } catch (err) { /* ignore */ }
  }

  start() {
    return new Promise((resolve, reject) => {
      if (this.proc && this.proc.exitCode === null) {
        return reject(new Error('Server is already running'));
      }
      const jar = this.jarPath();
      if (!fs.existsSync(jar)) {
        return reject(new Error('server.jar not found. Reinstall this server.'));
      }
      if (!system.javaInfo(true).installed) {
        this.pushLine('[BLUENODES] Cannot start: Java is not installed on this machine');
        this.pushLine('[BLUENODES] Install it with: sudo bluenodes install-java');
        this.lastError = { t: Date.now(), line: 'Java is not installed — run: sudo bluenodes install-java' };
        return reject(new Error('Java is not installed. Run "sudo bluenodes install-java" on the host.'));
      }
      isPortFree(this.port).then((free) => {
        if (!free) return reject(new Error('Port ' + this.port + ' is already in use on this machine'));
        this.writeEula();
        this.stopping = false;
        this.adopted = false;
        this.clearError();
        this.players.clear();
        this.lastStartedAt = Date.now();
        this.startedAt = Date.now();
        this.exitCode = null;
        this.exitedAt = null;
        try {
          const logFile = path.join(this.dir, 'console.log');
          if (fs.existsSync(logFile) && fs.statSync(logFile).size > 5 * 1024 * 1024) {
            fs.renameSync(logFile, path.join(this.dir, 'console.log.old'));
          }
          fs.writeFileSync(logFile, '');
        } catch (err) { /* ignore */ }

        this.setStatus('starting');
        this.pushLine('[BLUENODES] Starting ' + this.type + ' server ' + this.version +
          ' with ' + this.memory + 'MB RAM on port ' + this.port);
        this.pushLine('[BLUENODES] java -Xms' + this.memory + 'M -Xmx' + this.memory + 'M ' +
          JAVA_FLAGS.join(' ') + ' -jar ' + path.basename(jar) + ' nogui');

        let proc;
        try {
          proc = spawn('java', [
            '-Xms' + this.memory + 'M',
            '-Xmx' + this.memory + 'M',
            ...JAVA_FLAGS,
            '-jar', path.basename(jar),
            'nogui'
          ], {
            cwd: this.dir,
            env: Object.assign({}, process.env, { TERM: 'dumb' }),
            stdio: ['pipe', 'pipe', 'pipe']
          });
        } catch (err) {
          this.setStatus('stopped');
          this.pushLine('[BLUENODES] Failed to launch java: ' + err.message);
          return reject(err);
        }

        this.proc = proc;
        this.emit('spawn', this.snapshot());

        const onData = (chunk) => {
          const text = chunk.toString('utf8');
          for (const raw of text.split(/\r?\n/)) {
            if (!raw.trim()) continue;
            this.pushLine(raw);
            this.detect(raw);
          }
        };
        proc.stdout.on('data', onData);
        proc.stderr.on('data', onData);

        proc.on('error', (err) => {
          this.pushLine('[BLUENODES] Process error: ' + err.message);
          if (err.code === 'ENOENT') {
            this.pushLine('[BLUENODES] Java is not installed on this machine. Run: bluenodes install-java');
            this.setStatus('stopped');
          }
          reject(err);
        });

        proc.on('exit', (code, signal) => {
          this.exitCode = code;
          this.exitedAt = Date.now();
          this.proc = null;
          this.players.clear();
          this.stats = { cpu: 0, memory: 0 };
          this.pushLine('[BLUENODES] Server stopped (exit code ' + code +
            (signal ? ', signal ' + signal : '') + ')');
          this.setStatus('stopped');
          this.emit('exit', { code, signal, intentional: this.stopping });
        });

        setTimeout(() => {
          if (this.status === 'starting') this.setStatus('running');
        }, 45000);

        resolve(this.snapshot());
      }).catch(reject);
    });
  }

  detect(line) {
    if (/Done \([\d.]+s\)!|For help, type "help"/.test(line)) {
      if (this.status !== 'running') {
        this.setStatus('running');
        this.pushLine('[BLUENODES] Server is online on port ' + this.port);
      }
    }
    const join = line.match(PLAYER_JOIN);
    if (join) this.players.add(join[1]);
    const leave = line.match(PLAYER_LEAVE);
    if (leave) this.players.delete(leave[1]);
  }

  livePid() {
    if (this.proc && this.proc.exitCode === null) return this.proc.pid;
    return this.adoptedPid || null;
  }

  send(command) {
    if (this.adopted && !this.proc) {
      throw new Error('Console input is not available for servers started outside the panel');
    }
    if (!this.proc || !this.proc.stdin || this.proc.stdin.destroyed) {
      throw new Error('Server is not running');
    }
    const cmd = String(command || '').replace(/[\r\n]+/g, '').trim();
    if (!cmd) throw new Error('Empty command');
    this.proc.stdin.write(cmd + '\n');
    this.pushLine('[console] > ' + cmd);
    return { ok: true, command: cmd };
  }

  async stop(force) {
    if (!this.proc && this.adoptedPid) {
      this.setStatus('stopping');
      this.pushLine('[BLUENODES] Asking external process ' + this.adoptedPid + ' to stop');
      try { process.kill(this.adoptedPid, 'SIGTERM'); } catch (err) { /* ignore */ }
      for (let i = 0; i < 30; i++) {
        if (!isAlive(this.adoptedPid)) break;
        await new Promise((r) => setTimeout(r, 500));
      }
      if (isAlive(this.adoptedPid)) {
        try { process.kill(this.adoptedPid, 'SIGKILL'); } catch (err) { /* ignore */ }
      }
      this.adoptedPid = null;
      this.adopted = false;
      this.startedAt = null;
      this.setStatus('stopped');
      this.emit('exit', { code: 0, signal: 'SIGTERM', intentional: true });
      return { ok: true, adopted: true };
    }
    if (!this.proc || this.proc.exitCode !== null) {
      this.setStatus('stopped');
      return { ok: true, already: true };
    }
    this.stopping = true;
    this.setStatus('stopping');
    try {
      this.proc.stdin.write('stop\n');
      this.pushLine('[BLUENODES] Sent stop command, waiting for safe shutdown...');
    } catch (err) {
      try { this.proc.kill('SIGTERM'); } catch (e) { /* ignore */ }
    }
    const child = this.proc;
    const wait = (ms) => new Promise((r) => setTimeout(r, ms));
    for (let i = 0; i < 40; i++) {
      if (!child || child.exitCode !== null) return { ok: true };
      await wait(500);
    }
    this.pushLine('[BLUENODES] Server did not stop in time, sending SIGTERM');
    try { child.kill('SIGTERM'); } catch (err) { /* ignore */ }
    for (let i = 0; i < 20; i++) {
      if (child.exitCode !== null) return { ok: true };
      await wait(500);
    }
    this.pushLine('[BLUENODES] Force killing server process');
    try { child.kill('SIGKILL'); } catch (err) { /* ignore */ }
    return { ok: true, forced: true };
  }

  async kill() {
    this.stopping = true;
    if (this.proc) {
      try { this.proc.kill('SIGKILL'); } catch (err) { /* ignore */ }
      return;
    }
    if (this.adoptedPid) {
      try { process.kill(this.adoptedPid, 'SIGKILL'); } catch (err) { /* ignore */ }
      this.adoptedPid = null;
      this.setStatus('stopped');
    }
  }

  updateStats() {
    const pid = this.livePid();
    if (!pid) {
      this.stats = { cpu: 0, memory: 0 };
      return this.stats;
    }
    const s = system.processStats(pid, this._prevStats);
    this._prevStats = { ticks: s.ticks, at: s.at };
    this.stats = { cpu: Math.round((s.cpu || 0) * 10) / 10, memory: s.memory || 0 };
    return this.stats;
  }

  snapPlayers() {
    return Array.from(this.players);
  }

  snapshot() {
    let jarBytes = 0;
    try {
      const jar = this.jarPath();
      if (fs.existsSync(jar)) jarBytes = fs.statSync(jar).size;
    } catch (err) { /* ignore */ }
    if (!this._diskCache || Date.now() - this._diskCache.at > 60000) {
      let bytes = 0;
      try { bytes = system.panelDiskUsage(this.dir); } catch (err) { /* ignore */ }
      this._diskCache = { at: Date.now(), bytes };
    }
    const diskBytes = this._diskCache.bytes;
    return {
      id: this.id,
      name: this.name,
      port: this.port,
      version: this.version,
      type: this.type,
      memory: this.memory,
      status: this.status,
      players: this.snapPlayers(),
      online: this.players.size,
      uptime: this.status === 'running' || this.status === 'starting'
        ? Math.floor((Date.now() - (this.startedAt || Date.now())) / 1000) : 0,
      startedAt: this.startedAt,
      exitCode: this.exitCode,
      autoRestart: this.autoRestart,
      eula: this.eula,
      pid: this.livePid(),
      adopted: this.adopted,
      lastError: this.lastError,
      createdAt: this.createdAt,
      address: null,
      jar: path.basename(this.jarPath()),
      jarText: formatBytes(jarBytes),
      disk: formatBytes(diskBytes),
      cpu: this.stats.cpu,
      ram: this.stats.memory,
      ramText: formatBytes(this.stats.memory)
    };
  }
}

function isAlive(pid) {
  try {
    process.kill(pid, 0);
    return true;
  } catch (err) {
    return false;
  }
}

function readProperties(dir) {
  const file = path.join(dir, 'server.properties');
  const out = {};
  try {
    for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
      if (!line || line.startsWith('#')) continue;
      const idx = line.indexOf('=');
      if (idx < 0) continue;
      out[line.slice(0, idx).trim()] = line.slice(idx + 1);
    }
  } catch (err) { /* ignore */ }
  return out;
}

function writeProperties(dir, props) {
  const file = path.join(dir, 'server.properties');
  const current = readProperties(dir);
  const merged = Object.assign({}, current, props);
  const known = [
    'server-port', 'motd', 'max-players', 'online-mode', 'difficulty', 'gamemode',
    'pvp', 'view-distance', 'simulation-distance', 'spawn-protection', 'level-name',
    'enable-command-block', 'allow-flight', 'white-list', 'hardcore', 'level-seed',
    'enable-rcon', 'player-idle-timeout', 'force-gamemode'
  ];
  const order = known.filter((k) => merged[k] !== undefined);
  const rest = Object.keys(merged).filter((k) => !known.includes(k));
  const lines = ['#Minecraft server properties', '#Edited by BLUENODES'];
  for (const key of order.concat(rest)) lines.push(key + '=' + merged[key]);
  fs.writeFileSync(file, lines.join('\n') + '\n');
}

function serverAddress(port, host) {
  return (host || system.localIp()) + ':' + port;
}

module.exports = { MinecraftServer, readProperties, writeProperties, serverAddress, LOG_LIMIT };
